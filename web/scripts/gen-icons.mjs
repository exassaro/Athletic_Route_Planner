// The GATHO icon set (blueprint Phase 5b amendment 2): the icons the UI uses, copied from pixelarticons (MIT,
// pinned in package.json) into src/brand/icons.ts as path data, so only these ship and no package code does.
// `npm run gen:icons` after changing the list; src/brand/icons.test.ts fails if the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ICONS = {
  search: "search", menu: "menu", close: "close",
  chevronLeft: "chevron-left", chevronRight: "chevron-right", chevronDown: "chevron-down", chevronUp: "chevron-up",
  plus: "plus", minus: "minus", more: "more-vertical", check: "check",
  warning: "warning-diamond", alert: "square-alert", info: "info-box",
  download: "download", share: "share", link: "link", copy: "copy", externalLink: "external-link", bookmark: "bookmark",
  undo: "undo", redo: "redo", edit: "pencil", trash: "trash", drag: "drag-and-drop",
  gps: "gps", mapPin: "map-pin", map: "map", fit: "scale", flag: "flag",
  clock: "clock", climb: "trending-up", sliders: "sliders", sun: "sun", moon: "moon",
  pointToPoint: "arrow-right", outAndBack: "arrows-horizontal", loop: "reload",
};

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("pixelarticons/package.json"));

/** The path data of one pixelarticons SVG: <path> elements only (anything else would be lost, so it is refused). */
export function iconPaths(file) {
  const svg = readFileSync(join(pkgDir, "svg", `${file}.svg`), "utf8");
  const shapes = [...svg.matchAll(/<(\w+)[\s>]/g)].map((m) => m[1]).filter((t) => t !== "svg");
  const other = shapes.filter((t) => t !== "path");
  if (other.length) throw new Error(`${file}.svg has <${other.join(">, <")}>: only <path> is supported`);
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${file}.svg is not on the 24 px grid`);
  return [...svg.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]).join("");
}

export function render() {
  const { version } = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
  const lines = Object.entries(ICONS).map(([name, file]) => `  ${name}: ${JSON.stringify(iconPaths(file))}, // ${file}`);
  return `// Generated by scripts/gen-icons.mjs from pixelarticons ${version} (MIT, (c) Gerrit Halfmann). Do not edit.\n` +
    `export const ICON_PATHS = {\n${lines.join("\n")}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "brand", "icons.ts");
  writeFileSync(out, render());
  console.log(`${Object.keys(ICONS).length} icons -> src/brand/icons.ts`);
}
