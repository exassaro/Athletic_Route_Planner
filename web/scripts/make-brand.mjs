// The GATHO brand, all from the grids in web/brand/logo.json (blueprint Phase 5b amendments 23 to 28):
//   src/brand/logo.ts            the wordmark and icon as path data for <Wordmark> (committed; a test checks it)
//   public/icons/                icon.svg, icon-512, icon-maskable-512, icon-192, icon-180, icon-32 (gitignored)
//   public/favicon.ico           16 and 32 (gitignored)
//   public/brand/og.png          the OpenGraph image (gitignored)
// Runs before dev and build. PNGs are sampled nearest-neighbour, never smoothed. The OpenGraph tagline is set in the
// Geist font bundled with Next (next/og works offline), because a system font would differ from machine to machine.
import { crc32, deflateSync } from "node:zlib";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const spec = JSON.parse(readFileSync(join(root, "brand", "logo.json"), "utf8"));
const { letters, word, dot } = spec;

const COLS = 5;
const ROWS = 7;
const GAP = 1;
const MARGIN = 1;
export const WORDMARK = { w: 2 * MARGIN + word.length * COLS + (word.length - 1) * GAP, h: 2 * MARGIN + ROWS };

/** The wordmark's cells by part, the one-cell margin included. */
export function wordmarkCells() {
  const out = { ink: [], o: [], dot: [] };
  [...word].forEach((ch, i) => {
    const left = MARGIN + i * (COLS + GAP);
    const last = i === word.length - 1;
    letters[ch].forEach((row, y) => [...row].forEach((c, x) => {
      if (c === "1") out[last ? "o" : "ink"].push([left + x, MARGIN + y]);
    }));
    if (last) out.dot.push([left + dot.column, MARGIN + dot.row]);
  });
  return out;
}

/** The icon on an n x n grid: the O centred, its dot in the middle; the corners cut unless it is a full square. */
export function iconCells(n, cutCorners) {
  const left = (n - COLS) / 2;
  const top = (n - ROWS) / 2;
  const out = { tile: [], o: [], dot: [[left + dot.column, top + dot.row]] };
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    if (cutCorners && (x === 0 || x === n - 1) && (y === 0 || y === n - 1)) continue;
    out.tile.push([x, y]);
  }
  letters.O.forEach((row, y) => [...row].forEach((c, x) => { if (c === "1") out.o.push([left + x, top + y]); }));
  return out;
}

/** Cells as horizontal runs: [x, y, width]. */
function runs(cells) {
  const out = [];
  for (const [x, y] of [...cells].sort((a, b) => a[1] - b[1] || a[0] - b[0])) {
    const last = out[out.length - 1];
    if (last && last[1] === y && last[0] + last[2] === x) last[2]++;
    else out.push([x, y, 1]);
  }
  return out;
}

const path = (cells) => runs(cells).map(([x, y, w]) => `M${x} ${y}h${w}v1h-${w}z`).join("");
const paths = (parts) => Object.fromEntries(Object.entries(parts).map(([k, v]) => [k, path(v)]));

/** src/brand/logo.ts */
export function render() {
  const data = {
    wordmark: { ...WORDMARK, rows: ROWS, ...paths(wordmarkCells()) },
    icon: { n: spec.icon.grid, ...paths(iconCells(spec.icon.grid, true)) },
  };
  return "// Generated by scripts/make-brand.mjs from brand/logo.json. Do not edit.\n" +
    `export const LOGO = ${JSON.stringify(data, null, 1)} as const;\n`;
}

const rgba = (hex) => [...[1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)), 255];

/** RGBA pixels of the icon at `size`, each pixel the cell under its centre. */
export function iconPixels(size, n, cutCorners) {
  const parts = iconCells(n, cutCorners);
  const colour = new Array(n * n).fill(null);
  for (const part of ["tile", "o", "dot"]) for (const [x, y] of parts[part]) colour[y * n + x] = rgba(spec.icon[part]);
  const px = new Uint8Array(size * size * 4);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const c = colour[Math.floor(((y + 0.5) * n) / size) * n + Math.floor(((x + 0.5) * n) / size)];
    if (c) px.set(c, (y * size + x) * 4);
  }
  return px;
}

function png(size, px) {
  const stride = size * 4;
  const raw = Buffer.alloc((stride + 1) * size);
  for (let y = 0; y < size; y++) Buffer.from(px.buffer, y * stride, stride).copy(raw, y * (stride + 1) + 1);
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body) >>> 0);
    return Buffer.concat([len, body, crc]);
  };
  const head = Buffer.alloc(13);
  head.writeUInt32BE(size, 0); head.writeUInt32BE(size, 4); head[8] = 8; head[9] = 6; // 8-bit RGBA
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", head),
    chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}

/** An .ico holding PNGs. */
function ico(images) {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach(([size, data], i) => {
    const at = 6 + 16 * i;
    head[at] = size; head[at + 1] = size;
    head.writeUInt16LE(1, at + 4);
    head.writeUInt16LE(32, at + 6);
    head.writeUInt32LE(data.length, at + 8);
    head.writeUInt32LE(offset, at + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...images.map(([, data]) => data)]);
}

function iconSvg() {
  const parts = paths(iconCells(spec.icon.grid, true));
  const body = ["tile", "o", "dot"].map((p) => `<path fill="${spec.icon[p]}" d="${parts[p]}"/>`).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${spec.icon.grid} ${spec.icon.grid}" shape-rendering="crispEdges">${body}</svg>\n`;
}

/** The wordmark as boxes on whole pixels, the tagline under it. */
async function openGraph() {
  const { ImageResponse } = await import("next/og.js");
  const { width, height, cell, background, muted, tagline } = spec.og;
  const left = Math.round((width - WORDMARK.w * cell) / 2);
  const top = Math.round((height - WORDMARK.h * cell) / 2) - 50;
  const el = (style, children) => ({ type: "div", props: { style: { display: "flex", ...style }, children } });
  const boxes = Object.entries(wordmarkCells()).flatMap(([part, cells]) => runs(cells).map(([x, y, w]) => el({
    position: "absolute", left: left + x * cell, top: top + y * cell, width: w * cell, height: cell, background: spec.og[part],
  })));
  const line = el({ position: "absolute", left: 0, top: top + WORDMARK.h * cell + 28, width, justifyContent: "center",
    fontSize: 40, color: muted }, tagline);
  const image = new ImageResponse(el({ position: "relative", width: "100%", height: "100%", background }, [...boxes, line]),
    { width, height });
  return Buffer.from(await image.arrayBuffer());
}

export async function main() {
  const logoModule = join(root, "src", "brand", "logo.ts");
  const next = render();
  // only when it changed, so a checkout with CRLF endings is not rewritten by every build
  if (!existsSync(logoModule) || readFileSync(logoModule, "utf8").replaceAll("\r\n", "\n") !== next) writeFileSync(logoModule, next);

  const icons = join(root, "public", "icons");
  const brand = join(root, "public", "brand");
  mkdirSync(icons, { recursive: true });
  mkdirSync(brand, { recursive: true });
  const { grid, maskableGrid } = spec.icon;
  for (const [name, size, n, cut] of [
    ["icon-512.png", 512, grid, true],
    ["icon-maskable-512.png", 512, maskableGrid, false],
    ["icon-192.png", 192, grid, true],
    ["icon-180.png", 180, grid, false],          // apple-touch-icon: iOS rounds it, and paints see-through corners black
    ["icon-32.png", 32, grid, true],
  ]) writeFileSync(join(icons, name), png(size, iconPixels(size, n, cut)));
  writeFileSync(join(icons, "icon.svg"), iconSvg());
  writeFileSync(join(root, "public", "favicon.ico"), ico([16, 32].map((s) => [s, png(s, iconPixels(s, grid, true))])));
  writeFileSync(join(brand, "og.png"), await openGraph());
  console.log("GATHO brand -> src/brand/logo.ts, public/icons/, public/favicon.ico, public/brand/og.png");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
