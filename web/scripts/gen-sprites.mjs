// The GATHO sprites as SVG path data (blueprint Phase 5b amendment 6): web/brand/sprites.json (the approved
// strings) -> src/brand/sprites.ts, one path per palette colour (each row's runs of a colour merged into one
// rectangle) plus the depth layer: every non-outline pixel offset by 0.3 px, black at the sprite's opacity.
// `npm run gen:sprites` after sprites.json changes; src/brand/sprites.test.ts fails if the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function runs(rows, keep) {
  const out = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let n = 1;
      while (x + n < row.length && row[x + n] === ch) n++;
      if (keep(ch)) out.push({ ch, x, y, n });
      x += n;
    }
  });
  return out;
}

const fmt = (v) => String(Math.round(v * 10) / 10);

export function sprite(rows, palette, depthOpacity) {
  const byColour = {};
  for (const r of runs(rows, (ch) => ch !== ".")) {
    const fill = palette[r.ch];
    byColour[fill] = (byColour[fill] ?? "") + `M${r.x} ${r.y}h${r.n}v1h-${r.n}z`;
  }
  const depth = runs(rows, (ch) => ch !== "." && ch !== "O").map((r) => `M${fmt(r.x + 0.3)} ${fmt(r.y + 0.3)}h${r.n}v1h-${r.n}z`).join("");
  return { w: rows[0].length, h: rows.length, depthOpacity, depth, layers: Object.entries(byColour).map(([fill, d]) => ({ fill, d })) };
}

export function render() {
  const s = JSON.parse(readFileSync(join(root, "brand", "sprites.json"), "utf8"));
  const data = {
    sneaker: sprite(s.sneaker.rows, s.sneaker.palette, s.sneaker.depthOpacity),
    runner: sprite(s.runner.rows, s.runner.palette, s.runner.depthOpacity),
    runCycle: s.runCycle.frames.map((f) => sprite(f, s.runner.palette, s.runner.depthOpacity)),
  };
  return "// Generated by scripts/gen-sprites.mjs from brand/sprites.json (approved art, docs/reports/phase5b/sprites.md).\n" +
    "// Do not edit.\n" +
    "export type SpriteData = { w: number; h: number; depthOpacity: number; depth: string; layers: { fill: string; d: string }[] };\n\n" +
    `export const SPRITES = ${JSON.stringify(data, null, 1)} as const satisfies { sneaker: SpriteData; runner: SpriteData; runCycle: readonly SpriteData[] };\n\n` +
    `export const RUN_FRAME_MS = ${s.runCycle.frameMs};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "src", "brand", "sprites.ts"), render());
  console.log("sprites -> src/brand/sprites.ts");
}
