// The GATHO sprites as SVG path data (blueprint Phase 5b amendment 6): web/brand/sprites.json (the approved
// strings) -> src/brand/sprites.ts, one path per palette colour (each row's runs of a colour merged into one
// rectangle) plus the depth layer: every non-outline pixel offset by 0.3 px, black at the sprite's opacity.
// `npm run gen:sprites` after sprites.json changes; src/brand/sprites.test.ts fails if the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function runs(rows, keep) {
  const out = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let n = 1;
      while (x + n < row.length && row[x + n] === ch) n++;
      if (keep(ch)) out.push({ ch, x, y, n });
      x += n;
    }
  });
  return out;
}

const fmt = (v) => String(Math.round(v * 10) / 10);

export function sprite(rows, palette, depthOpacity) {
  const byColour = {};
  for (const r of runs(rows, (ch) => ch !== ".")) {
    const fill = palette[r.ch];
    byColour[fill] = (byColour[fill] ?? "") + `M${r.x} ${r.y}h${r.n}v1h-${r.n}z`;
  }
  const depth = runs(rows, (ch) => ch !== "." && ch !== "O").map((r) => `M${fmt(r.x + 0.3)} ${fmt(r.y + 0.3)}h${r.n}v1h-${r.n}z`).join("");
  return { w: rows[0].length, h: rows.length, depthOpacity, depth, layers: Object.entries(byColour).map(([fill, d]) => ({ fill, d })) };
}

// The loading strip's canvas, in sprite pixels: room for the dust, the sneaker at its furthest forward, the dots.
export const CYCLE_CANVAS = { w: 57, h: 20, shoeX: 10, shoeY: 3 };
const DUST = [                                  // [x, y, w, h] per frame: puffs that drift back and up
  [[7, 17, 2, 2], [4, 18, 1, 1]],
  [[5, 15, 3, 2], [8, 18, 1, 1]],
  [[2, 14, 2, 2], [7, 17, 3, 2], [6, 13, 1, 1]],
  [[1, 13, 1, 1], [4, 15, 3, 2], [8, 18, 2, 1]],
];
const DOTS = [47, 51, 55].map((x) => [x, 15, 2, 2]);
const DOTS_LIT = [3, 1, 2, 3];                  // the first frame, shown with reduced motion, has all three
const boxes = (list) => list.map(([x, y, w, h]) => `M${x} ${y}h${w}v${h}h-${w}z`).join("");

/** One cycle frame: the approved sneaker with whole columns moved (amendment 17). No pixel is redrawn. */
export function shifted(rows, step, { raise, lift, dx }) {
  const { w, h, shoeX, shoeY } = CYCLE_CANVAS;
  const last = rows[0].length - 1;
  const out = Array.from({ length: h }, () => Array(w).fill("."));
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === ".") return;
    const up = lift + (raise === "toe" ? Math.floor(x / step) : raise === "heel" ? Math.floor((last - x) / step) : 0);
    out[shoeY + y - up][shoeX + x + dx] = ch;
  }));
  return out.map((r) => r.join(""));
}

export function render() {
  const s = JSON.parse(readFileSync(join(root, "brand", "sprites.json"), "utf8"));
  const { rows, palette, depthOpacity } = s.sneaker;
  const data = {
    sneaker: sprite(rows, palette, depthOpacity),
    cycle: s.cycle.frames.map((f, i) => ({
      ...sprite(shifted(rows, s.cycle.step, f), palette, depthOpacity),
      dust: boxes(DUST[i]), dots: boxes(DOTS.slice(0, DOTS_LIT[i])), dotsFaint: boxes(DOTS.slice(DOTS_LIT[i])),
    })),
  };
  return "// Generated by scripts/gen-sprites.mjs from brand/sprites.json (approved art, docs/reports/phase5b/sprites.md).\n" +
    "// Do not edit.\n" +
    "export type SpriteData = { w: number; h: number; depthOpacity: number; depth: string; layers: { fill: string; d: string }[] };\n" +
    "export type CycleFrame = SpriteData & { dust: string; dots: string; dotsFaint: string };\n\n" +
    `export const SPRITES = ${JSON.stringify(data, null, 1)} as const satisfies { sneaker: SpriteData; cycle: readonly CycleFrame[] };\n\n` +
    `export const CYCLE_FRAME_MS = ${s.cycle.frameMs};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "src", "brand", "sprites.ts"), render());
  console.log("sprites -> src/brand/sprites.ts");
}
